/**
 * Mathematics visual campaign — regenerate the live status block of the handover report (2026-10-12).
 *
 * Every number in docs/history/MATHEMATICS_VISUAL_HANDOVER.md between the STATUS markers is COMPUTED from the repository (the same registry calls the tutor
 * uses, docs/qa/mathematics-visual-campaign/tiers.json, and git), never typed by hand. Run it at the end of every batch, then commit the doc with the batch.
 *
 *   npx tsx scripts/math/campaign-tools/update-handover.ts
 *
 * Only the text between <!-- STATUS:BEGIN --> and <!-- STATUS:END --> is rewritten.
 */
import { execSync } from 'node:child_process'
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { join } from 'node:path'
import { lookupConceptVisualBinding, getConceptSceneGenerator } from '@/lib/teaching/visualRegistry'
import { CONCEPT_SCENE_OVERRIDES } from '@/lib/teaching/visual/conceptSceneParams'

const root = process.cwd()
const DOC = join(root, 'docs/history/MATHEMATICS_VISUAL_HANDOVER.md')
const kg = JSON.parse(readFileSync(join(root, 'docs/mathematics/kg/graph.json'), 'utf8'))
const nodes: Array<{ id: string; name: string }> = kg.concepts ?? kg.nodes ?? kg
const tiers: Record<string, 'E' | 'H' | 'N'> = JSON.parse(readFileSync(join(root, 'docs/qa/mathematics-visual-campaign/tiers.json'), 'utf8')).tiers
const authored = new Set<string>(CONCEPT_SCENE_OVERRIDES as string[])
const covered = (id: string) => { if (authored.has(id)) return true; try { if (lookupConceptVisualBinding(id)) return true } catch { /* none */ } try { if (getConceptSceneGenerator(id)) return true } catch { /* none */ } return false }
const RESERVED = new Set(['math.linalg.vector-addition', 'math.func.linear-function']) // canary + test fixture: deliberately figure-less

const rows = nodes.map((n) => ({ id: n.id, name: n.name, domain: n.id.split('.')[1], tier: tiers[n.id] ?? 'N', covered: covered(n.id) }))
const pct = (a: number, b: number) => `${((100 * a) / b).toFixed(1)}%`
const tot = (t: string) => rows.filter((r) => r.tier === t).length
const cov = (t: string) => rows.filter((r) => r.tier === t && r.covered).length
const done = rows.filter((r) => r.covered).length
const eh = tot('E') + tot('H'), ehDone = cov('E') + cov('H')
const gapsH = rows.filter((r) => r.tier === 'H' && !r.covered && !RESERVED.has(r.id))
const byDomain = new Map<string, string[]>()
for (const g of gapsH) byDomain.set(g.domain, [...(byDomain.get(g.domain) ?? []), g.id.split('.').slice(2).join('.')])
const domainLines = [...byDomain.entries()].sort((a, b) => b[1].length - a[1].length).map(([d, ids]) => `- **${d}** (${ids.length}): ${ids.join(', ')}`)
const modules = readdirSync(join(root, 'src/lib/teaching/sceneGenerators')).filter((f) => /^mathCoreScenesB\d+\.ts$/.test(f)).map((f) => Number(/B(\d+)/.exec(f)![1])).sort((a, b) => a - b)
const lastBatch = modules[modules.length - 1]
const git = (cmd: string) => { try { return execSync(cmd, { cwd: root, encoding: 'utf8' }).trim() } catch { return '(git unavailable)' } }
const recent = git(`git log -8 --format="- %h %ad %s" --date=short --grep="Mathematics visuals batch"`).split('\n').map((l) => (l.length > 190 ? `${l.slice(0, 187)}…` : l)).join('\n')
const head = git('git rev-parse --short HEAD'), branch = git('git rev-parse --abbrev-ref HEAD'), dirty = git('git status --short').split('\n').filter(Boolean).length
const remainingBatches = Math.ceil(gapsH.length / 13)

const block = `<!-- STATUS:BEGIN (generated by scripts/math/campaign-tools/update-handover.ts — do not edit by hand) -->
**Generated:** ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC · git ${branch} @ ${head} · uncommitted files: ${dirty}

| Measure | Done | Total | Percent |
|---|---|---|---|
| All concepts with a fixed figure | ${done} | ${rows.length} | **${pct(done, rows.length)}** |
| Tier E (essential) | ${cov('E')} | ${tot('E')} | ${pct(cov('E'), tot('E'))} (the 2 left are the reserved canary + fixture) |
| Tier H (helpful) | ${cov('H')} | ${tot('H')} | **${pct(cov('H'), tot('H'))}** |
| Tier N (no figure needed, optional) | ${cov('N')} | ${tot('N')} | ${pct(cov('N'), tot('N'))} |
| Campaign target (E + H) | ${ehDone} | ${eh} | **${pct(ehDone, eh)}** |

- Last batch module: **B${lastBatch}**. Tier-H concepts still to do: **${gapsH.length}** → about **${remainingBatches}** more batches of 13.
- Next batch is **B${lastBatch + 1}**.

**Tier-H concepts still uncovered, by domain (largest first):**

${domainLines.join('\n')}

**Recent batch commits (newest first):**

${recent}
<!-- STATUS:END -->`

const doc = readFileSync(DOC, 'utf8')
const next = doc.replace(/<!-- STATUS:BEGIN[\s\S]*?<!-- STATUS:END -->/, block)
if (next === doc && !doc.includes('STATUS:BEGIN')) { console.error('STATUS markers not found in', DOC); process.exit(1) }
writeFileSync(DOC, next)
console.log(`updated ${DOC}: ${done}/${rows.length} concepts (${pct(done, rows.length)}), tier H ${cov('H')}/${tot('H')}, next batch B${lastBatch + 1}`)
