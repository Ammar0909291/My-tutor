export interface CorrectControl {
  readonly text: string
  readonly source: string
  readonly occurrences: number
}

export type CorruptionMethod = 'DROP_FACTOR' | 'WRONG_EXPONENT' | 'SYMBOL_SUBSTITUTION'

export interface RejectionCase {
  readonly text: string
  readonly sourceEquation: string
  readonly corruptionMethod: CorruptionMethod
  readonly brokenBecause: string
}

export type MustNotFireReason =
  | 'QUESTIONED'
  | 'QUOTED_AS_LEARNER_ERROR'
  | 'NEGATED_ASSERTION'
  | 'COMPARED_NOT_ASSERTED'

export interface MustNotFireControl {
  readonly text: string
  readonly reason: MustNotFireReason
  readonly source: string
  readonly note: string
}

